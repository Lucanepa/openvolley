/**
 * The game PIN mail of POST /api/match/send-pin (server.js): the PIN notice
 * the scorer sees before the coin toss ("Send to my email").
 *
 * - To the signed-in scorer's OWN confirmed account address only; an address
 *   in the request is never read.
 * - Only for a match the account created or edits (as POST /api/match/send-info).
 * - The server keeps the game PIN hashed (lib/pinHash.js), so it cannot read
 *   it back: the app sends the PIN it shows, and the mail goes out only when
 *   that PIN matches the stored one. An unchecked PIN is never mailed.
 * - The rest of the text comes from the stored match, never from the request.
 *
 * send-info stays as it is: the match information without the PIN (it once
 * mailed any typed address a text with the game PIN; that is gone for good).
 */

/** The sentence of the PIN notice (frontend pinNotice.writeDown). */
export const PIN_MAIL_SENTENCE = 'Please write the PIN down somewhere: it is needed to recover the match and/or to reopen it.'

/**
 * The PIN of a request body: 4 to 12 digits (the app makes 6), as a string,
 * else null. A number is taken as its digits.
 */
export function pinFromBody (value) {
  const s = typeof value === 'number' && Number.isInteger(value) && value >= 0
    ? String(value)
    : typeof value === 'string' ? value.trim() : ''
  return /^\d{4,12}$/.test(s) ? s : null
}

// One line of stored match text: no line breaks (a header or a forged line in
// the mail), at most `max` characters, 'N/A' when empty.
const line = (v, max = 120) => (typeof v === 'string' && v.trim() ? v.trim().replace(/[\r\n]+/g, ' ').slice(0, max) : 'N/A')

// The full name only: a short name stored before its retirement (26.11.2026) is not mailed
const teamLine = (t) => line(t?.name)

/**
 * @param {object} m           the stored match: game_n, home_team, away_team, league
 * @param {string} pin         the CHECKED game PIN
 * @param {{ date: string, time: string }} when  lib/contact.js matchMailDateTime
 * @returns {{ subject: string, text: string }}
 */
export function pinMailText (m, pin, when) {
  const gameN = Number.isInteger(m?.game_n) || (typeof m?.game_n === 'string' && /^\d+$/.test(m.game_n)) ? String(m.game_n) : 'N/A'
  const text = `
Game PIN
========

Game Number: ${gameN}
Home: ${teamLine(m?.home_team)}
Away: ${teamLine(m?.away_team)}
League: ${line(m?.league)}
Date: ${line(when?.date, 20)}
Time: ${line(when?.time, 20)}

Game PIN: ${pin}

${PIN_MAIL_SENTENCE}

---
Generated by eScoresheet
`.trim()
  return { subject: gameN === 'N/A' ? 'Game PIN eScoresheet' : `Game ${gameN} eScoresheet: game PIN`, text }
}

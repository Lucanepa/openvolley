const here = dirname(fileURLToPath(import.meta.url))
const BACKEND = join(here, '..')
const DB_DIR = join(BACKEND, 'db')
const sqlOf = (f) => readFileSync(join(DB_DIR, f), 'utf8')
// what the restored Supabase dump has and the synthetic schema leaves out (003 updates it)
const SYNC_LOG_SQL = `CREATE TABLE public.svrz_sync_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, status text, started_at timestamptz,
  finished_at timestamptz, message text);`
const BASE_SQL = readFileSync(join(here, 'fixtures', 'synthetic_schema.sql'), 'utf8') + '\n' + SYNC_LOG_SQL
const numbered = (from, to, { without = [] } = {}) => readdirSync(DB_DIR)
  .filter((f) => /^\d{3}_.*\.sql$/.test(f) && Number(f.slice(0, 3)) >= from && Number(f.slice(0, 3)) <= to && !without.includes(Number(f.slice(0, 3))))
  .sort()

  it('the backend\'s check: retried while the database cannot be reached, refreshed on demand, a change logged once', async () => {
    let down = true
    const real = new pg.Pool({ connectionString: at033.url, max: 1 })
    const pool = { query: (...args) => down ? Promise.reject(new Error('connect ECONNREFUSED (test)')) : real.query(...args) }
    const lines = []
    try {
      const st0 = await checkSchemaAtStart(pool, { log: quietLog(lines), retryMs: [20], recheckMs: 0 })
      assert.match(st0.error, /ECONNREFUSED/)
      assert.equal(schemaStatus().ready, false)
      await new Promise((resolve) => setTimeout(resolve, 100))
      assert.equal(lines.filter((l) => /schema not checked/.test(l)).length, 1, lines.join('\n')) // retried, logged once
      down = false
      await until(() => schemaStatus()?.ready === true)
      assert.match(lines.at(-1), new RegExp(`schema: db/${pad3(NEWEST)} applied`))

      // a guard disabled later: the cached state (under a minute old) first, then a fresh one
      await a.query('ALTER TABLE public.matches DISABLE TRIGGER matches_club_guard')
      assert.equal((await refreshSchemaStatus()).ready, true)
      const st = await refreshSchemaStatus({ maxAgeMs: 0 })
      assert.equal(st.ready, false)
      assert.ok(st.problems.some((p) => /matches_club_guard/.test(p)), st.problems.join('\n'))
      assert.equal(schemaStatus(), st)
      const n = lines.length
      assert.match(lines.at(-1), /matches_club_guard/)
      await refreshSchemaStatus({ maxAgeMs: 0 })
      assert.equal(lines.length, n, 'the same state is not logged again')
      await a.query('ALTER TABLE public.matches ENABLE TRIGGER matches_club_guard')
      assert.equal((await refreshSchemaStatus({ maxAgeMs: 0 })).ready, true)

      // the periodic check sees a change without being asked
      await checkSchemaAtStart(pool, { log: quietLog(lines), recheckMs: 30 })
      await a.query('ALTER TABLE public.matches DISABLE TRIGGER matches_club_guard')
      await until(() => schemaStatus()?.ready === false)
      await a.query('ALTER TABLE public.matches ENABLE TRIGGER matches_club_guard')
      await until(() => schemaStatus()?.ready === true)
    } finally {
      stopSchemaChecks()
      await a.query('ALTER TABLE public.matches ENABLE TRIGGER matches_club_guard')
      await real.end()
    }
    assert.equal(await refreshSchemaStatus(), schemaStatus(), 'stopped: no further checks')
  })

/**
 * scripts/migrate.mjs (the migration runner), db/current_definitions.sql,
 * lib/schemaVersion.js and scripts/check-schema.mjs.
 *
 * A database "at 033" is built the way restore.sh built one before the runner
 * existed (the synthetic schema standing in for the restored dump, then every
 * db/NNN_*.sql from 002 to 033); the reference is one with every numbered file
 * of this checkout run by hand; a "fresh" one is the synthetic schema alone,
 * which the runner builds from the numbered files. All must end in the same
 * schema, and a second run must change nothing. Then: a changed file is
 * refused, 007 or 011 run again by hand leaves no old trigger function behind
 * once the runner ran, a new file runs once in its own transaction, a database
 * that lacks the objects of a file up to 033 is not recorded as having it, an
 * older image on a newer database is not reported as broken, and the schema
 * check finds a missing or disabled guard.
 *
 * Nothing here assumes which file is the newest: a new db/NNN_*.sql needs no
 * change in this file (scratch files are numbered after the newest one).
 */

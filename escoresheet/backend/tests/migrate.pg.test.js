      const newer = await readSchemaState(a, { dbDir: dir })
      assert.equal(newer.ready, true, JSON.stringify(newer))
      assert.equal(newer.functionsChecked, true)

      // this checkout's db/ is the older image
      let older = await readSchemaState(a)
      assert.deepEqual(older.ahead, [NEWEST + 1])
      assert.equal(older.functionsChecked, false)
      assert.deepEqual(older.problems, [])

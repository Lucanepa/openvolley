/**
 * scripts/migrate.mjs (the migration runner), db/current_definitions.sql,
 * lib/schemaVersion.js and scripts/check-schema.mjs.
 *
 * A database "at 033" is built the way restore.sh builds one (the synthetic
 * schema standing in for the restored dump, then every db/NNN_*.sql from 002
 * on); a "fresh" one is the synthetic schema alone, which the runner builds
 * from the numbered files. Both must end in the same schema, and a second run
 * must change nothing. Then: a changed file is refused, 007 or 011 run again
 * by hand leaves no old trigger function behind once the runner ran, a new
 * file runs once in its own transaction, a database without the objects of
 * 032/033 is not recorded as being at 033, and the schema check finds a
 * missing or disabled guard.
 */
import { describe, it, before, after } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync, cpSync, mkdtempSync, rmSync, writeFileSync, readdirSync, appendFileSync, unlinkSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { execFile } from 'node:child_process'
import pg from 'pg'
import { SKIP_PG, createTestDatabase } from './helpers/pgTestDb.js'
import { migrate, unwrapTransaction, currentDefinitionProblems } from '../scripts/migrate.mjs'
import { migrationFiles, readSchemaState, schemaProblems, schemaCheckSql, checkSchemaAtStart } from '../lib/schemaVersion.js'

const here = dirname(fileURLToPath(import.meta.url))
const BACKEND = join(here, '..')
const DB_DIR = join(BACKEND, 'db')
const sqlOf = (f) => readFileSync(join(DB_DIR, f), 'utf8')
// what the restored Supabase dump has and the synthetic schema leaves out (003 updates it)
const SYNC_LOG_SQL = `CREATE TABLE public.svrz_sync_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, status text, started_at timestamptz,
  finished_at timestamptz, message text);`
const BASE_SQL = readFileSync(join(here, 'fixtures', 'synthetic_schema.sql'), 'utf8') + '\n' + SYNC_LOG_SQL
const numbered = (from, to) => readdirSync(DB_DIR)
  .filter((f) => /^\d{3}_.*\.sql$/.test(f) && Number(f.slice(0, 3)) >= from && Number(f.slice(0, 3)) <= to)
  .sort()
// restore.sh step 7: 002, then every file from 003 on, by hand (psql)
const AT_033_SQL = BASE_SQL + '\n' + numbered(2, 33).map(sqlOf).join('\n')
const AT_031_SQL = BASE_SQL + '\n' + numbered(2, 31).map(sqlOf).join('\n')
const quiet = () => {}

/** Everything of the public and auth schemas that a migration can change (not ov_meta: the record itself). */
async function snapshot (db) {
  const q = async (sql) => (await db.query(sql)).rows.map((r) => Object.values(r).join(' | '))
  return {
    columns: await q(`SELECT table_schema, table_name, column_name, data_type, udt_name, is_nullable, coalesce(column_default, '')
                        FROM information_schema.columns WHERE table_schema IN ('public', 'auth') ORDER BY 1, 2, 3`),
    constraints: await q(`SELECT conrelid::regclass::text, conname, pg_get_constraintdef(oid) FROM pg_constraint
                           WHERE connamespace IN ('public'::regnamespace, 'auth'::regnamespace) ORDER BY 1, 2`),
    indexes: await q(`SELECT indexrelid::regclass::text, pg_get_indexdef(indexrelid) FROM pg_index i JOIN pg_class c ON c.oid = i.indexrelid
                       WHERE c.relnamespace IN ('public'::regnamespace, 'auth'::regnamespace) ORDER BY 1`),
    triggers: await q(`SELECT tgrelid::regclass::text, tgname, tgenabled, pg_get_triggerdef(oid) FROM pg_trigger
                        WHERE NOT tgisinternal ORDER BY 1, 2`),
    functions: await q(`SELECT p.oid::regprocedure::text, pg_get_functiondef(p.oid) FROM pg_proc p
                         WHERE p.pronamespace IN ('public'::regnamespace, 'auth'::regnamespace) AND p.prokind = 'f' ORDER BY 1`)
  }
}
const records = async (db) => (await db.query('SELECT version, file, checksum, applied_at, baseline, last_run_at FROM ov_meta.schema_migrations ORDER BY version')).rows
const prosrc = async (db, fn) => (await db.query('SELECT prosrc FROM pg_proc WHERE oid = to_regprocedure($1)', [fn])).rows[0]?.prosrc ?? ''
/** A copy of db/ to change a file in. */
function dbDirCopy () {
  const dir = mkdtempSync(join(tmpdir(), 'ov-migrate-'))
  cpSync(DB_DIR, dir, { recursive: true })
  return dir
}
function runScript (script, args, env) {
  return new Promise((resolve) => {
    execFile(process.execPath, [join(BACKEND, 'scripts', script), ...args], { env: { ...process.env, ...env } },
      (err, stdout, stderr) => resolve({ code: err ? err.code : 0, stdout, stderr }))
  })
}

describe('migrate.mjs: files the runner accepts (no database)', () => {
  it('takes every numbered file from 002 on, unwrapping its own BEGIN / COMMIT, and keeps DO blocks', () => {
    for (const f of numbered(2, 999)) {
      const sql = sqlOf(f)
      const body = unwrapTransaction(sql, f)
      assert.equal(body.length, sql.length, `${f}: positions must stay the same`)
      assert.doesNotMatch(body, /^\s*(BEGIN|COMMIT)\s*;\s*$/m, `${f}: its own BEGIN / COMMIT is taken out`)
    }
    const body = unwrapTransaction("BEGIN;\nDO $$ BEGIN PERFORM 1; END $$;\nSELECT 'COMMIT;';\nCOMMIT;\n", 'x.sql')
    assert.match(body, /DO \$\$ BEGIN PERFORM 1; END \$\$;/)
    assert.match(body, /SELECT 'COMMIT;';/)
    assert.doesNotMatch(body, /^BEGIN;|^COMMIT;/m)
  })

  it('refuses psql meta-commands and any other transaction control', () => {
    for (const f of ['000_prelude.sql', '001_post_restore.sql', 'roles.sql']) {
      assert.throws(() => unwrapTransaction(sqlOf(f), f), /psql/, f)
    }
    assert.throws(() => unwrapTransaction('BEGIN;\nSELECT 1;\nCOMMIT;\nBEGIN;\nSELECT 2;\nCOMMIT;\n', 'x.sql'), /one transaction/)
    assert.throws(() => unwrapTransaction('SELECT 1;\nROLLBACK;\n', 'x.sql'), /ROLLBACK/)
    assert.throws(() => unwrapTransaction('BEGIN;\nSELECT 1;\n', 'x.sql'), /COMMIT/)
    assert.throws(() => unwrapTransaction("SELECT 'unterminated;\n", 'x.sql'), /unterminated/)
    assert.throws(() => unwrapTransaction('SELECT $q$ open;\n', 'x.sql'), /unterminated/)
  })

  it('current_definitions.sql holds every function more than one file defines, as of the newest one', async () => {
    assert.deepEqual(currentDefinitionProblems({ dbDir: DB_DIR }), [])
    const dir = dbDirCopy()
    try {
      // a later file that redefines a function current_definitions.sql holds
      writeFileSync(join(dir, '034_guard_v3.sql'), 'BEGIN;\nCREATE OR REPLACE FUNCTION public.ov_match_children_guard() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RETURN NEW; END $$;\nCOMMIT;\n')
      // and one that redefines a function only 007 had
      writeFileSync(join(dir, '035_guard.sql'), 'BEGIN;\nCREATE OR REPLACE FUNCTION public.ov_matches_guard() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RETURN NEW; END $$;\nCOMMIT;\n')
      // and one that drops a function current_definitions.sql would create again
      writeFileSync(join(dir, '036_no_void_trigger.sql'), 'BEGIN;\nDROP TRIGGER IF EXISTS events_apply_void ON public.events;\nDROP FUNCTION IF EXISTS public.ov_events_apply_void();\nCOMMIT;\n')
      const problems = currentDefinitionProblems({ dbDir: dir })
      assert.ok(problems.some((p) => /034_guard_v3\.sql/.test(p) && /ov_match_children_guard/.test(p)), problems.join('\n'))
      assert.ok(problems.some((p) => /ov_matches_guard/.test(p) && /007/.test(p) && /035/.test(p)), problems.join('\n'))
      assert.ok(problems.some((p) => /036_no_void_trigger\.sql drops function public\.ov_events_apply_void/.test(p)), problems.join('\n'))
      // the runner refuses before it connects
      await assert.rejects(migrate({ connectionString: 'postgres://nobody@127.0.0.1:1/none', dbDir: dir, log: quiet }), /current_definitions\.sql is not current/)
    } finally { rmSync(dir, { recursive: true, force: true }) }
  })

  it('lists the numbered files in order and refuses two files with one number', () => {
    const files = migrationFiles(DB_DIR)
    assert.equal(files[0].version, 0)
    assert.ok(files.every((f, i) => i === 0 || f.version > files[i - 1].version))
    const dir = dbDirCopy()
    try {
      writeFileSync(join(dir, '033_other.sql'), 'SELECT 1;\n')
      assert.throws(() => migrationFiles(dir), /033/)
    } finally { rmSync(dir, { recursive: true, force: true }) }
  })
})

describe('migrate.mjs on a database', { skip: SKIP_PG }, () => {
  let at033, fresh, at031
  let a, f, c
  let s033 // schema of the database at 033 before the runner ever ran

  before(async () => {
    at033 = await createTestDatabase('mig_at033', { schemaSql: AT_033_SQL })
    fresh = await createTestDatabase('mig_fresh', { schemaSql: BASE_SQL })
    at031 = await createTestDatabase('mig_at031', { schemaSql: AT_031_SQL })
    a = new pg.Client({ connectionString: at033.url })
    f = new pg.Client({ connectionString: fresh.url })
    c = new pg.Client({ connectionString: at031.url })
    await Promise.all([a.connect(), f.connect(), c.connect()])
    s033 = await snapshot(a)
  })
  after(async () => {
    await Promise.all([a, f, c].map((x) => x?.end().catch(() => {})))
    for (const d of [at033, fresh, at031]) await d?.drop()
  })

  it('first run at 033: records 000-033 without running them, current definitions change nothing', async () => {
    const r = await migrate({ connectionString: at033.url, log: quiet })
    assert.equal(r.baseline, 33)
    assert.deepEqual(r.applied, [])
    const rows = await records(a)
    assert.deepEqual(rows.map((x) => x.version), numbered(0, 33).map((x) => Number(x.slice(0, 3))))
    assert.ok(rows.every((x) => x.baseline && /^[0-9a-f]{64}$/.test(x.checksum)))
    // current_definitions.sql is exactly the newest numbered definitions
    assert.deepEqual(await snapshot(a), s033)
  })

  it('a fresh database builds from the numbered files and ends in the same schema', async () => {
    const r = await migrate({ connectionString: fresh.url, baseline: 1, log: quiet })
    assert.equal(r.baseline, 1)
    assert.deepEqual(r.applied, numbered(2, 33).map((x) => Number(x.slice(0, 3))))
    assert.deepEqual(await snapshot(f), s033)
    const rows = await records(f)
    assert.deepEqual(rows.filter((x) => x.baseline).map((x) => x.version), [0, 1])
  })

  it('a second run changes nothing', async () => {
    for (const [url, db] of [[at033.url, a], [fresh.url, f]]) {
      const before = await records(db)
      const r = await migrate({ connectionString: url, log: quiet })
      assert.equal(r.baseline, null)
      assert.deepEqual(r.applied, [])
      assert.deepEqual(await records(db), before)
      assert.deepEqual(await snapshot(db), s033)
    }
  })

  it('refuses a file that changed after it was recorded, and changes nothing', async () => {
    const dir = dbDirCopy()
    try {
      appendFileSync(join(dir, '007_scorer_accounts.sql'), '\n-- edited later\n')
      const before = await records(a)
      await assert.rejects(migrate({ connectionString: at033.url, dbDir: dir, log: quiet }), /007_scorer_accounts\.sql.*changed/s)
      assert.deepEqual(await records(a), before)
      const st = await readSchemaState(a, { dbDir: dir })
      assert.ok(st.changed.includes(7))
      assert.equal(st.ready, false)
    } finally { rmSync(dir, { recursive: true, force: true }) }
  })

  it('007 and 011 run again by hand: the old trigger functions are found, and the next run puts the current ones back', async () => {
    // a scorer who voided a point of a match that is closed now
    const { rows: [u] } = await a.query("INSERT INTO auth.users (email) VALUES ('scorer.one@example.invalid') RETURNING id")
    const { rows: [m] } = await a.query("INSERT INTO public.matches (external_id, status, test) VALUES ('m_runner_1', 'live', false) RETURNING id")
    await a.query("INSERT INTO public.events (match_id, external_id, set_index, type, seq, voided_at, voided_by, void_reason) VALUES ($1, 'm_runner_1:e:1', 1, 'point', 1, now(), $2, 'undo')", [m.id, u.id])
    await a.query("UPDATE public.matches SET status = 'final' WHERE id = $1", [m.id])
    assert.deepEqual(await schemaProblems(a), [])

    await a.query(sqlOf('007_scorer_accounts.sql'))
    await a.query(sqlOf('011_account_approvals.sql'))
    assert.doesNotMatch(await prosrc(a, 'public.ov_match_children_guard()'), /voided_by/)
    assert.doesNotMatch(await prosrc(a, 'public.ov_matches_void_approvals()'), /'beach'/)
    const problems = await schemaProblems(a)
    assert.ok(problems.some((p) => /ov_match_children_guard/.test(p)), problems.join('\n'))
    assert.ok(problems.some((p) => /ov_matches_void_approvals/.test(p)), problems.join('\n'))
    assert.ok(problems.some((p) => /ov_matches_close_audit/.test(p)), problems.join('\n'))
    // the account cannot be deleted: its void in the closed match is frozen by 007's guard
    await assert.rejects(a.query('DELETE FROM auth.users WHERE id = $1', [u.id]), /match is closed/)

    const r = await migrate({ connectionString: at033.url, log: quiet })
    assert.deepEqual(r.applied, [])
    assert.match(await prosrc(a, 'public.ov_match_children_guard()'), /voided_by/)
    assert.match(await prosrc(a, 'public.ov_matches_void_approvals()'), /'beach'/)
    assert.deepEqual(await schemaProblems(a), [])
    assert.deepEqual(await snapshot(a), s033)
    await a.query('DELETE FROM auth.users WHERE id = $1', [u.id])
    const { rows: [e] } = await a.query("SELECT voided_by FROM public.events WHERE external_id = 'm_runner_1:e:1'")
    assert.equal(e.voided_by, null)
  })

  it('030 run again by hand loses 031\'s SECURITY DEFINER; the next run puts it back', async () => {
    await a.query(sqlOf('030_manager_roles.sql'))
    const problems = await schemaProblems(a)
    assert.ok(problems.some((p) => /ov_manager_rows_changed/.test(p) && /SECURITY DEFINER/.test(p)), problems.join('\n'))
    await migrate({ connectionString: at033.url, log: quiet })
    assert.deepEqual(await schemaProblems(a), [])
  })

  it('--rerun 007 puts dropped guard triggers back and keeps the current functions', async () => {
    await a.query('DROP TRIGGER matches_guard ON public.matches; DROP TRIGGER events_closed_guard ON public.events')
    const problems = await schemaProblems(a)
    assert.ok(problems.some((p) => /matches_guard/.test(p) && /missing/.test(p)), problems.join('\n'))
    assert.ok(problems.some((p) => /events_closed_guard/.test(p)), problems.join('\n'))
    const r = await migrate({ connectionString: at033.url, rerun: [7], log: quiet })
    assert.deepEqual(r.rerun, [7])
    assert.deepEqual(await schemaProblems(a), [])
    assert.deepEqual(await snapshot(a), s033)
    const row = (await records(a)).find((x) => x.version === 7)
    assert.ok(row.last_run_at)
    await assert.rejects(migrate({ connectionString: at033.url, rerun: [99], log: quiet }), /099|99/)
    await assert.rejects(migrate({ connectionString: at033.url, rerun: [1], log: quiet }), /restore/)
  })

  it('the schema check finds a disabled trigger and a missing index; check-schema.mjs exits 1', async () => {
    await a.query('ALTER TABLE public.matches DISABLE TRIGGER matches_club_guard')
    await a.query('DROP INDEX public.notifications_once_uidx')
    const problems = await schemaProblems(a)
    assert.ok(problems.some((p) => /matches_club_guard/.test(p) && /disabled/.test(p)), problems.join('\n'))
    assert.ok(problems.some((p) => /notifications_once_uidx/.test(p)), problems.join('\n'))
    // the same query for psql (restore.sh)
    const { rows } = await a.query(schemaCheckSql())
    assert.deepEqual(rows.map((x) => x.problem), problems)
    const cli = await runScript('check-schema.mjs', [], { DATABASE_URL: at033.url })
    assert.equal(cli.code, 1)
    assert.match(cli.stdout + cli.stderr, /matches_club_guard/)
    const printed = await runScript('check-schema.mjs', ['--print-sql'], { DATABASE_URL: '' })
    assert.equal(printed.code, 0)
    assert.equal(printed.stdout.trim(), schemaCheckSql().trim())

    await a.query('ALTER TABLE public.matches ENABLE TRIGGER matches_club_guard')
    await a.query('CREATE UNIQUE INDEX notifications_once_uidx ON public.notifications (user_id, kind, subject_user_id)')
    assert.deepEqual(await schemaProblems(a), [])
    const ok = await runScript('check-schema.mjs', [], { DATABASE_URL: at033.url })
    assert.equal(ok.code, 0, ok.stdout + ok.stderr)
  })

  it('a new file: behind until it runs, runs once in its own transaction, recorded; a failing one leaves nothing', async () => {
    const dir = dbDirCopy()
    try {
      writeFileSync(join(dir, '034_runner_probe.sql'),
        '-- a test migration\nBEGIN;\nSET LOCAL lock_timeout = \'5s\';\nCREATE TABLE IF NOT EXISTS public.runner_probe (id int PRIMARY KEY);\nINSERT INTO public.runner_probe VALUES (1) ON CONFLICT DO NOTHING;\nCOMMIT;\n')
      let st = await readSchemaState(a, { dbDir: dir })
      assert.equal(st.expected, 34)
      assert.equal(st.applied, 33)
      assert.deepEqual(st.pending, [34])
      assert.equal(st.ready, false)
      const status = await runScript('migrate.mjs', ['--status', '--db-dir', dir], { OV_MIGRATE_DATABASE_URL: at033.url })
      assert.equal(status.code, 3, status.stdout + status.stderr)
      assert.match(status.stdout, /034_runner_probe\.sql/)

      const r = await migrate({ connectionString: at033.url, dbDir: dir, log: quiet })
      assert.deepEqual(r.applied, [34])
      st = await readSchemaState(a, { dbDir: dir })
      assert.deepEqual(st.pending, [])
      assert.equal(st.ready, true)
      assert.deepEqual((await migrate({ connectionString: at033.url, dbDir: dir, log: quiet })).applied, [])

      // the second statement fails: the first is rolled back with it, and 035 is not recorded
      writeFileSync(join(dir, '035_runner_fails.sql'),
        'BEGIN;\nCREATE TABLE public.runner_half (id int);\nSELECT 1 / 0;\nCOMMIT;\n')
      await assert.rejects(migrate({ connectionString: at033.url, dbDir: dir, log: quiet }), /035_runner_fails\.sql.*line 3.*division by zero/s)
      assert.equal((await a.query("SELECT to_regclass('public.runner_half') AS t")).rows[0].t, null)
      assert.deepEqual((await records(a)).map((x) => x.version).slice(-1), [34])
      unlinkSync(join(dir, '035_runner_fails.sql'))

      // a file with its own ROLLBACK is refused before anything runs
      writeFileSync(join(dir, '035_runner_rollback.sql'), 'CREATE TABLE public.runner_rb (id int);\nROLLBACK;\n')
      await assert.rejects(migrate({ connectionString: at033.url, dbDir: dir, log: quiet }), /ROLLBACK/)
      assert.equal((await a.query("SELECT to_regclass('public.runner_rb') AS t")).rows[0].t, null)
      unlinkSync(join(dir, '035_runner_rollback.sql'))

      // the image without 034 (an older one, after a rollback): its runner refuses, so its
      // older current_definitions.sql can never replace newer function bodies
      await assert.rejects(migrate({ connectionString: at033.url, log: quiet }), /034.*(newer|does not have)/s)
      st = await readSchemaState(a)
      assert.deepEqual(st.ahead, [34])
      assert.deepEqual(st.pending, [])
    } finally {
      rmSync(dir, { recursive: true, force: true })
      await a.query('DROP TABLE IF EXISTS public.runner_probe; DELETE FROM ov_meta.schema_migrations WHERE version = 34')
    }
  })

  it('first run without the objects of 032 and 033: refused unless told where the database stands', async () => {
    await assert.rejects(migrate({ connectionString: at031.url, log: quiet }), /--baseline/)
    assert.equal((await c.query("SELECT to_regclass('ov_meta.schema_migrations') AS t")).rows[0].t, null)
    await assert.rejects(migrate({ connectionString: at031.url, baseline: 33, log: quiet }), /032|033/)
    const r = await migrate({ connectionString: at031.url, baseline: 31, log: quiet })
    assert.deepEqual(r.applied, [32, 33])
    assert.deepEqual(await snapshot(c), s033)
    await assert.rejects(migrate({ connectionString: at031.url, baseline: 31, log: quiet }), /first run/)
    await assert.rejects(migrate({ connectionString: at031.url, baseline: 34, log: quiet }), /baseline/)
  })

  it('takes an advisory lock: a second runner waits, then gives up', async () => {
    const holder = new pg.Client({ connectionString: at033.url })
    await holder.connect()
    try {
      await holder.query("SELECT pg_advisory_lock(hashtextextended('openvolley:migrate', 0))")
      await assert.rejects(migrate({ connectionString: at033.url, lockWaitMs: 300, log: quiet }), /another migration run/)
    } finally { await holder.end() }
  })

  it('refuses to run as a role that does not own the schema; the backend role reads the state', async () => {
    const appUrl = await at033.createAppRole()
    const appRole = new URL(appUrl).username
    await assert.rejects(migrate({ connectionString: appUrl, log: quiet }), /owner|ov_owner/)
    const app = new pg.Client({ connectionString: appUrl })
    await app.connect()
    try {
      assert.equal((await readSchemaState(app)).record, 'unreadable')
      await migrate({ connectionString: at033.url, appRole, log: quiet })
      const st = await readSchemaState(app)
      assert.equal(st.record, 'ok')
      assert.equal(st.ready, true, JSON.stringify(st))
      await assert.rejects(app.query("INSERT INTO ov_meta.schema_migrations (version, file, checksum) VALUES (99, 'x', repeat('0', 64))"), /permission denied/)
      const lines = []
      const pool = new pg.Pool({ connectionString: appUrl, max: 1 })
      try {
        const state = await checkSchemaAtStart(pool, { log: { log: (l) => lines.push(l), warn: (l) => lines.push(l), error: (l) => lines.push(l) } })
        assert.equal(state.ready, true)
        assert.match(lines.join('\n'), /schema: db\/033/)
      } finally { await pool.end() }
    } finally { await app.end() }
  })
})

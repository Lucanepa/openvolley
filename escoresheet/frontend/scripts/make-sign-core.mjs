#!/usr/bin/env node
/**
 * Generates the backend's copies of the Sign on phone code
 * (docs/qr-signing-spec.md 4.5 and 4.7). The backend's Docker context has no
 * frontend/, so it gets them as files of its own:
 *
 *   ../backend/lib/signSessions.js  ESM copy of electron/signSessionCore.cjs
 *   ../backend/lib/signPage.js      public/sign/{index.html,sign.js,sign.css} as strings
 *
 * Usage:
 *   node scripts/make-sign-core.mjs           # write both files
 *   node scripts/make-sign-core.mjs --check   # exit 1 when either is out of date
 *
 * src/utils/__tests__/signCoreCopy.test.js fails when a copy drifts.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const HERE = dirname(fileURLToPath(import.meta.url))
export const FRONTEND_DIR = join(HERE, '..')
export const CORE_SRC = join(FRONTEND_DIR, 'electron', 'signSessionCore.cjs')
export const PAGE_DIR = join(FRONTEND_DIR, 'public', 'sign')
export const CORE_OUT = join(FRONTEND_DIR, '..', 'backend', 'lib', 'signSessions.js')
export const PAGE_OUT = join(FRONTEND_DIR, '..', 'backend', 'lib', 'signPage.js')
export const PAGE_FILES = ['index.html', 'sign.js', 'sign.css']

const BANNER = (from) => `// GENERATED by escoresheet/frontend/scripts/make-sign-core.mjs from\n// ${from}. Do not edit: change the source, rerun.\n`

/** The ESM text of backend/lib/signSessions.js. */
export function renderSignCore(source = readFileSync(CORE_SRC, 'utf8')) {
  const text = source.replace(/\r\n/g, '\n')
  if (!text.startsWith("'use strict'\n")) throw new Error("signSessionCore.cjs must start with 'use strict'")
  if (/\brequire\s*\(/.test(text.replace(/\/\/.*$/gm, '').replace(/\/\*[\s\S]*?\*\//g, ''))) {
    throw new Error('signSessionCore.cjs must not require() anything')
  }
  const at = text.lastIndexOf('\nmodule.exports = {')
  if (at < 0 || !text.trimEnd().endsWith('}')) throw new Error('signSessionCore.cjs must end with module.exports = { ... }')
  const body = text.slice("'use strict'\n".length, at)
  const exportsList = text.slice(at + '\nmodule.exports = '.length).trimEnd()
  return `${BANNER('escoresheet/frontend/electron/signSessionCore.cjs')}${body}\nexport ${exportsList}\n`
}

/** The ESM text of backend/lib/signPage.js. */
export function renderSignPage(dir = PAGE_DIR) {
  const files = {}
  for (const name of PAGE_FILES) {
    const p = join(dir, name)
    files[name] = existsSync(p) ? readFileSync(p, 'utf8').replace(/\r\n/g, '\n') : null
  }
  const missing = PAGE_FILES.filter((n) => files[n] === null)
  if (missing.length === PAGE_FILES.length) {
    files['index.html'] = '<!doctype html><meta charset="utf-8"><title>OpenVolley</title><p>Phone signing is not built yet.</p>\n'
    files['sign.js'] = ''
    files['sign.css'] = ''
  } else if (missing.length) {
    throw new Error(`public/sign is missing ${missing.join(', ')}`)
  }
  return `${BANNER('escoresheet/frontend/public/sign/{index.html,sign.js,sign.css}')}//
// The phone page of Sign on phone, served by the cloud backend at /sign (the
// LAN relays serve the same files from their dist/). Same-origin with
// /api/sign/*, so it needs no CORS entry.
export const SIGN_PAGE_FILES = Object.freeze({
  'index.html': { type: 'text/html; charset=utf-8', body: ${JSON.stringify(files['index.html'])} },
  'sign.js': { type: 'text/javascript; charset=utf-8', body: ${JSON.stringify(files['sign.js'])} },
  'sign.css': { type: 'text/css; charset=utf-8', body: ${JSON.stringify(files['sign.css'])} }
})

/** The file of a /sign* path (/sign, /sign/, /sign/index.html, /sign/sign.js, /sign/sign.css), or null. */
export function signPageFile(pathname) {
  if (pathname === '/sign' || pathname === '/sign/' || pathname === '/sign/index.html') return SIGN_PAGE_FILES['index.html']
  if (pathname === '/sign/sign.js') return SIGN_PAGE_FILES['sign.js']
  if (pathname === '/sign/sign.css') return SIGN_PAGE_FILES['sign.css']
  return null
}
`
}

function main() {
  const check = process.argv.includes('--check')
  const outputs = [[CORE_OUT, renderSignCore()], [PAGE_OUT, renderSignPage()]]
  let stale = 0
  for (const [path, text] of outputs) {
    const current = existsSync(path) ? readFileSync(path, 'utf8') : null
    if (current === text) continue
    if (check) {
      console.error(`out of date: ${path}`)
      stale++
    } else {
      writeFileSync(path, text)
      console.log(`wrote ${path}`)
    }
  }
  if (stale) process.exit(1)
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main()
